// ---------------------------------------------------------------------------
// The screenpack
// ---------------------------------------------------------------------------
//
// The game's data folder is assembled at build time rather than checked in. The
// text files (.def, .cfg) are hand-written and live in tools/screenpack/data;
// the binary ones (.sff sprites, .fnt fonts) are generated by gen.py, which
// draws the art itself and writes real MUGEN files.
//
// Writing the binary formats at build time keeps a 24 KB blob of generated
// sprites out of the repository and, more usefully, keeps the generator and the
// engine's loader as two independent readings of the same spec -- a shared
// misreading would produce a file that round-trips perfectly and that no real
// MUGEN tool can open.

val screenpackDir = layout.projectDirectory.dir("../tools/screenpack")
val screenpackSource = screenpackDir.dir("data")
val screenpackGenerator = screenpackDir.file("gen.py")
val generatedScreenpack = layout.buildDirectory.dir("generated/screenpack")
// Gen.py's raw output is staged outside the assets root, so that the root holds
// only the tree that actually ships. Anything left inside it would be packaged
// into the APK verbatim.
val stagedScreenpack = layout.buildDirectory.dir("screenpack-staging")

// MUGEN's own sound files, if the player has supplied any.
//
// The same arrangement the roster has: third-party files that this repository does not
// redistribute, kept out of the tree and used when present. The generator copies them
// into the screenpack byte for byte. It writes no sound of its own, so a build without
// `local_sounds/` has no sound banks rather than synthesised stand-ins.
val suppliedSoundsDir = layout.projectDirectory.dir("../local_sounds")

val generateScreenpackBinaries by tasks.registering(Exec::class) {
    val outputDir = stagedScreenpack.get().asFile
    inputs.dir(screenpackSource)
    inputs.file(screenpackGenerator)
    // Re-run when the player's own sounds change, which they do far less often than the
    // generator but must not be ignored when they do.
    if (suppliedSoundsDir.asFile.isDirectory) inputs.dir(suppliedSoundsDir)
    outputs.dir(outputDir)
    doFirst { outputDir.mkdirs() }
    commandLine("python3", screenpackGenerator.asFile.absolutePath, outputDir.absolutePath,
        suppliedSoundsDir.asFile.absolutePath)
}

// Assembles what actually ships: <build>/generated/screenpack/mugen/data/...
// The engine opens its files relative to the "mugen" asset root, so the
// directory shape here is part of the contract with AssetFileSource.
val assembleScreenpack by tasks.registering(Copy::class) {
    dependsOn(generateScreenpackBinaries)
    from(stagedScreenpack)
    from(screenpackSource) {
        include("*.def", "*.cfg")
    }
    val destination = generatedScreenpack.map { it.dir("mugen/data") }
    into(destination)
    // Copy only adds. Drop the sound banks first so a removed local_sounds/ cannot
    // leave an old bank in the build output and keep shipping it.
    doFirst {
        val dir = destination.get().asFile
        for (name in listOf("system.snd", "common.snd", "fight.snd")) {
            dir.resolve(name).delete()
        }
    }
}

// ---------------------------------------------------------------------------
// Characters
// ---------------------------------------------------------------------------
//
// There is no character generator. The grid's cells come from select.def, and
// every fighter behind them is a community character the player downloads into
// local_chars/ -- see the task at the bottom of this file. A character is a
// folder of .def/.sff/.air/.cns/.cmd that the engine's loader reads at runtime;
// nothing about one is compiled or generated.

// ---------------------------------------------------------------------------
// Stages
// ---------------------------------------------------------------------------
//
// Stages are a sibling of chars/ in a MUGEN game folder, not part of the
// screenpack: select.def names them and a character may bring its own, so they
// are staged and copied the same way the roster is.

val stagesDir = layout.projectDirectory.dir("../tools/stages")
val stagesGenerator = stagesDir.file("gen.py")
val stagedStages = layout.buildDirectory.dir("stages-staging")

val generateStages by tasks.registering(Exec::class) {
    val outputDir = stagedStages.get().asFile
    inputs.file(stagesGenerator)
    outputs.dir(outputDir)
    doFirst { outputDir.mkdirs() }
    commandLine("python3", stagesGenerator.asFile.absolutePath, outputDir.absolutePath)
}

// <build>/generated/screenpack/mugen/stages/<id>/...
val assembleStages by tasks.registering(Copy::class) {
    dependsOn(generateStages)
    from(stagedStages)
    into(generatedScreenpack.map { it.dir("mugen/stages") })
}

// Community characters: the player's own downloaded character folders, kept
// in <repo>/local_chars/ (gitignored, never committed). Anything in there
// rides into the APK the same way the starter roster does, which is how a
// downloaded MUGEN character becomes playable without entering the source
// tree. An absent or empty folder adds nothing.
val localCharsDir = rootProject.projectDir.resolve("local_chars")

// A device round-trip needs the engine on the phone, not the player's whole
// character collection. The roster is ~1.3 GB of assets, so a full APK does not
// fit beside the copy already installed on a nearly-full phone -- which is the
// only reason a device test used to be impossible without freeing storage first.
// Naming folders here packages just those and nothing else:
//
//     gradle -Panifight.devChars=kfm,dbz_goku :app:installDebug
//
// Folders left out are simply absent, which the select screen already handles:
// select.def names characters the player has not downloaded yet as a matter of
// course (see the entries with no folder in local_chars/), so a slim build is
// the same situation the roster is in before anyone downloads anything. The
// whole character still ships -- only the packaging is narrower.
//
// Unset means every folder, which is the shipping default.
val devChars: List<String>? =
    (findProperty("anifight.devChars") as String?)
        ?.split(',')
        ?.map { it.trim() }
        ?.filter { it.isNotEmpty() }
        ?.takeIf { it.isNotEmpty() }

val assembleLocalChars by tasks.registering(Copy::class) {
    onlyIf { localCharsDir.listFiles()?.isNotEmpty() == true }
    val destination = generatedScreenpack.map { it.dir("mugen/chars") }
    // Which list this output was built from, so a change to it can be noticed.
    // `Copy` only ever adds, so without this a slim build would sit on top of a
    // previous full one and still carry 1.3 GB of characters.
    val listMarker = layout.buildDirectory.file("local-chars-list.txt").get().asFile
    val wanted = devChars?.joinToString(",") ?: "all"

    // Stated as an input so switching the list re-runs the copy; a Copy whose
    // source filter changed would otherwise look up to date.
    inputs.property("devChars", wanted)
    from(localCharsDir) {
        if (devChars != null) devChars.forEach { include("$it/**") }
    }
    into(destination)
    doFirst {
        if (listMarker.takeIf { it.isFile }?.readText()?.trim() != wanted) {
            destination.get().asFile.deleteRecursively()
        }
    }
    doLast {
        listMarker.parentFile.mkdirs()
        listMarker.writeText(wanted)
    }
}

// Community stages, from the same arrangement: <repo>/local_stages/ (gitignored),
// overlaid after the generated ones so a supplied stage with the same name wins.
// A stage is a .def naming the .sff beside it, so the folder is copied flat.
val localStagesDir = rootProject.projectDir.resolve("local_stages")
val assembleLocalStages by tasks.registering(Copy::class) {
    onlyIf { localStagesDir.listFiles()?.isNotEmpty() == true }
    from(localStagesDir)
    into(generatedScreenpack.map { it.dir("mugen/stages") })
}

android {
    sourceSets.getByName("main") {
        assets.srcDir(generatedScreenpack)
    }
}

// AGP's asset merge does not know the directory above is a task output, so the
// dependency has to be stated rather than inferred.
tasks.matching { it.name.startsWith("merge") && it.name.endsWith("Assets") }.configureEach {
    dependsOn(assembleScreenpack)
    dependsOn(assembleStages)
    dependsOn(assembleLocalChars)
    dependsOn(assembleLocalStages)
}
